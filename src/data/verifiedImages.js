export function getVerifiedDestination(id) {
  return VERIFIED_DESTINATIONS[id] || null;
}

export function getVerifiedDestinationImage(id) {
  const dest = VERIFIED_DESTINATIONS[id];
  return (dest && dest.image) ? dest.image : DESTINATION_FALLBACK_IMAGE;
}

export function getVerifiedState(idOrSlug) {
  if (!idOrSlug) return null;
  const key = String(idOrSlug).toLowerCase();
  return VERIFIED_STATES[key] || null;
}

export function getVerifiedStateImage(idOrSlug) {
  const s = getVerifiedState(idOrSlug);
  return (s && s.image) ? s.image : DESTINATION_FALLBACK_IMAGE;
}
